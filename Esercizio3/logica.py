# Modulo che raggruppa le varie funzionalità di logica matematica o conversione

def area_rettangolo(base, altezza):
    """Calcola l'area di un rettangolo data base e altezza."""
    return base * altezza

def perimetro_rettangolo(base, altezza):
    """Calcola il perimetro di un rettangolo data base e altezza."""
    return (base + altezza) * 2

def celsius_a_fahrenheit(celsius):
    """Converte una temperatura da gradi Celsius a Fahrenheit."""
    return (celsius * 9 / 5) + 32
